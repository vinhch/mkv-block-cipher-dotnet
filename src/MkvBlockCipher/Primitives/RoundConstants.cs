namespace MkvBlockCipher.Primitives;

// Rev2025 key-schedule constants C0 (left chain) and C1 (right chain), in block byte order.
internal static class RoundConstants
{
    internal static ReadOnlySpan<byte> Left(int blockBytes) => blockBytes switch
    {
        16 => Left128,
        32 => Left256,
        _ => throw new ArgumentOutOfRangeException(nameof(blockBytes)),
    };

    internal static ReadOnlySpan<byte> Right(int blockBytes) => blockBytes switch
    {
        16 => Right128,
        32 => Right256,
        _ => throw new ArgumentOutOfRangeException(nameof(blockBytes)),
    };

    private static ReadOnlySpan<byte> Left128 =>
    [
        0x93, 0x02, 0xEE, 0x91, 0x1A, 0x2A, 0xD9, 0x8C,
        0xAD, 0x13, 0xE7, 0x94, 0x8A, 0xD8, 0xB3, 0xB2,
